package jp.co.nsco.basearchitecture.core.error

/**
 * エラー表示時にユーザーへ提示する操作候補。
 *
 * UiErrorAction は、Dialog やエラー画面に表示するボタン、
 * または ViewModel がエラー後に受け付ける操作の種類を表す。
 *
 * ■ 設計上の意図
 *   エラー文言と操作候補を分離し、
 *   画面側が actions を見て必要なボタンを構成できるようにする。
 *
 *   具体的なボタン文言や見た目は UI 側で決定し、
 *   UiErrorAction は操作の意味だけを表す。
 */
enum class UiErrorAction {

    /**
     * エラー表示を閉じる。
     *
     * 復旧操作を行わず、Dialog やエラー表示のみを閉じる場合に使用する。
     */
    Close,

    /**
     * 直前の処理を再試行する。
     *
     * 通信失敗、一時的な保存失敗など、
     * 同じ操作を再実行することで復旧できる可能性がある場合に使用する。
     */
    Retry,

    /**
     * アプリまたは画面の状態を初期化してやり直す。
     *
     * 状態不整合や復旧困難なエラーに対して、
     * 再起動・再初期化を促す場合に使用する。
     */
    Restart,

    /**
     * 現在の処理をスキップする。
     *
     * 任意処理の失敗や、後続処理に進めることを許可する場合に使用する。
     */
    Skip
}